assert.match(cleaner, /RESIDUAL_SCAN_ENTRY_LIMIT: usize = 250_000/);
assert.match(cleaner, /RESIDUAL_SCAN_TOTAL_TIMEOUT: Duration = Duration::from_secs\(30\)/);
