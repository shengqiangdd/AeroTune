assert.ok(deletion.indexOf("validate_residual_root(target)?") < deletion.indexOf('"cmd"'));
assert.match(deletion, /"takeown"[\s\S]*cleanup_timeout,\s*\)\?/);
assert.match(deletion, /"icacls"[\s\S]*cleanup_timeout,\s*\)\?/);
assert.doesNotMatch(deletion, /let _ = crate::util::run_checked_with_timeout/);
assert.match(command, /if !confirmed \{\s*return Ok\(false\)/);
